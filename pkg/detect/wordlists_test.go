package detect

import (
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

func TestWordSetListsHaveNoDuplicates(t *testing.T) {
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	lists := 0
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		ast.Inspect(af, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 1 {
				return true
			}
			if id, ok := call.Fun.(*ast.Ident); !ok || id.Name != "wordSet" {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			s, err := strconv.Unquote(lit.Value)
			if err != nil {
				t.Fatal(err)
			}
			lists++
			seen := map[string]bool{}
			for _, w := range strings.Fields(s) {
				if seen[w] {
					t.Errorf("%s: duplicate word %q in wordSet list", fset.Position(lit.Pos()), w)
				}
				seen[w] = true
			}
			return true
		})
	}
	if lists < 50 {
		t.Fatalf("found only %d wordSet lists, the source scan is broken", lists)
	}
}
